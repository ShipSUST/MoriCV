import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { CATEGORY_SCHEMA } from '../src/shared/schema.js';
import { compileCategoryContract, hydrateCategoryContract } from '../src/shared/categories/runtime-contract.js';
import { FIXED_FIELDS } from '../src/shared/ordinary-fields.js';

export function renderCategoryRuntime() {
  const contract = JSON.stringify(compileCategoryContract(CATEGORY_SCHEMA), null, 2);
  const hydrateSource = hydrateCategoryContract.toString().replaceAll('\r\n', '\n');
  return `// Generated by scripts/category-runtime.mjs; edit shared/categories or ordinary-fields instead.\n(() => {\n  globalThis.ResumeHelperCategories = (${hydrateSource})(${contract}, ${JSON.stringify(FIXED_FIELDS, null, 2)});\n})();\n`;
}
export async function writeCategoryRuntime() {
  await writeFile(new URL('../src/shared/category-runtime.js', import.meta.url), renderCategoryRuntime());
}
export async function checkCategoryRuntime() {
  const actual = await readFile(new URL('../src/shared/category-runtime.js', import.meta.url), 'utf8');
  if (actual.replaceAll('\r\n', '\n') !== renderCategoryRuntime()) throw new Error('大类运行契约已过期，请运行 npm run generate:categories。');
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await writeCategoryRuntime();
