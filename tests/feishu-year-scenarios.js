import { siteProfile } from '/src/shared/schema.js';

export async function runFeishuYears() {
  if (location.hostname !== '127.0.0.1') throw new Error('Anonymous fixture only');
  const checks = [], timings = [];
  const check = (name, ok) => { if (!ok) throw new Error(name); checks.push(name); globalThis.__recordProgress = { checks: [...checks] }; };
  const awards = Array.from({ length: 14 }, (_, i) => ({ id: `anonymous.award.${i}`, name: `匿名奖项${i}`, description: `匿名描述${i}`, start: `${1990 + i}/04/10` }));
  const profile = siteProfile({ entries: [], records: { awards } });
  const originalProfile = JSON.stringify(profile);
  const settings = { overwriteExisting: false, confidenceThreshold: 78, rejectedMatches: [] };
  const rows = () => [...document.querySelectorAll('[data-kind="honor"] .resumeEditForm-item')];
  const date = row => row.querySelector('input[placeholder="YYYY"]');
  const field = (row, id) => row.querySelector(`[id="${id}"]`);
  const otherSnapshot = () => JSON.stringify([...document.querySelectorAll('[data-kind]:not([data-kind="honor"]) input, [data-kind]:not([data-kind="honor"]) textarea, .atsx-date-picker-period-month-label')].map(el => el.value ?? el.textContent));
  const others = otherSnapshot();
  const run = (command, payload = {}) => new Promise((resolve, reject) => {
    const started = performance.now(), timer = setTimeout(() => reject(new Error(`${command} timeout`)), 114000);
    globalThis.__resumeHelperListener({ type: 'RESUME_HELPER_COMMAND', command, payload: { profile, settings, ...payload } }, null, result => {
      clearTimeout(timer); timings.push({ command, ms: Math.round(performance.now() - started) });
      result?.error ? reject(new Error(result.error)) : resolve(result);
    });
  });
  const fill = (i = 0, extra = {}) => run('fillRecord', { collection: 'awards', recordId: awards[i].id, resetTransaction: true, ...extra });
  const initial = rows()[0];
  field(initial, 'honorName').value = awards[0].name;
  field(initial, 'honorDescription').value = awards[0].description;
  date(initial).dataset.delay = '40';
  const stale = document.createElement('div'); stale.className = 'atsx-date-picker-panel'; stale.dataset.cy = 'unrelatedDropdown'; stale.dataset.stale = 'true';
  stale.innerHTML = '<div class="atsx-date-picker-panel-body-year"><div class="atsx-date-picker-panel-body-cell-content">1990</div></div>';
  let staleClicked = false; stale.onclick = () => { staleClicked = true; }; document.body.append(stale);
  const scanned = await run('scan');
  check('year scan suggests configured date without writing', scanned.suggestions.some(s => s.entryId === awards[0].id && s.label === awards[0].start) && date(initial).value === '');
  const repaired = await fill();
  check('delayed year picker pages backwards and repairs only empty date', repaired.filled.length === 1 && date(initial).value === '1990' && rows().length === 1);
  check('year driver ignores unrelated stale panels', !staleClicked && stale.isConnected);
  check('success expected value is the actual year, not full JSON date', repaired.filled[0].expectedValue === '1990');
  const repeated = await fill(0, { resetTransaction: false });
  check('repeat year record does not duplicate or ask false conflict', repeated.filled.length === 0 && !repeated.requiresConfirmation && rows().length === 1);
  check('year undo clears only date and retains existing text', (await run('undo')).failedCount === 0 && date(initial).value === '' && field(initial, 'honorName').value === awards[0].name);
  stale.remove(); delete date(initial).dataset.delay;
  const batch = await run('fillCollection', { collection: 'awards', resetTransaction: true });
  check('14 awards fill with separate exact year precision', rows().length === 14 && rows().every((r, i) => date(r).value === awards[i].start.slice(0, 4)) && batch.filled.length === 40 && batch.skipped.every(s => s.reason === '字段已有内容'));
  const changed = structuredClone(profile); changed.records.awards[0].description = '匿名变更';
  const conflict = await fill(0, { profile: changed, resetTransaction: false, settings: { ...settings, overwriteExisting: true } });
  check('existing text conflict still requires confirmation', conflict.requiresConfirmation && conflict.filled.length === 0);
  check('batch undo preserves original group and removes only added groups', (await run('undo')).failedCount === 0 && rows().length === 1 && date(initial).value === '');
  date(initial).focus(); date(initial).click();
  await new Promise(resolve => setTimeout(resolve, 60));
  const target = await run('fillTarget', { entry: { id: 'anonymous.date', label: '获奖时间', value: awards[0].start, optionValues: [] } });
  check('targeted child uses same year picker', target.success && date(initial).value === '1990');
  check('target undo restores blank year', (await run('undo')).failedCount === 0 && date(initial).value === '');
  await fill(); date(initial).focus();
  check('target repeat needs no false full-date conflict', (await run('fillTarget', { entry: { id: 'anonymous.date', label: '获奖时间', value: awards[0].start, optionValues: [] } })).success);
  check('target repeat undo retains its pre-existing year', (await run('undo')).failedCount === 0 && date(initial).value === '1990');
  initial.querySelector('.atsx-date-picker-clear').click();
  date(initial).dataset.disabledYear = '1990';
  const failed = await fill();
  check('disabled year is rejected without false success', !failed.filled.length && failed.skipped.some(s => s.reason.includes('年份选项不可用')) && date(initial).value === '');
  const next = await fill(1, { resetTransaction: false });
  check('failure does not prevent next record', next.filled.length === 3 && date(rows()[1]).value === '1991');
  check('error continuation undo retains original record', (await run('undo')).failedCount === 0 && rows().length === 1);
  delete date(initial).dataset.disabledYear;
  date(initial).dataset.reject = '1';
  const rejected = await fill();
  check('selection without committed value is not success', rejected.filled.length === 0 && rejected.skipped.some(s => s.reason.includes('年份写入未确认')) && date(initial).value === '');
  delete date(initial).dataset.reject;
  date(initial).dataset.rewrite = '1';
  const rewritten = await fill();
  check('site-rewritten year is never falsely confirmed', rewritten.filled.length === 0 && date(initial).value === '1991');
  check('failed changed year remains available for undo', (await run('undo')).failedCount === 0 && date(initial).value === '');
  delete date(initial).dataset.rewrite;
  date(initial).dataset.ambiguous = '1';
  const ambiguous = await fill();
  check('multiple panels for one field fail closed', ambiguous.filled.length === 0 && date(initial).value === '' && ambiguous.skipped.some(s => s.reason.includes('当前字段')));
  delete date(initial).dataset.ambiguous;
  const future = structuredClone(profile); future.records.awards[0].start = '2041-09';
  const futureResult = await fill(0, { profile: future });
  check('year pages forward and accepts supplied month precision', futureResult.filled.length === 1 && date(initial).value === '2041');
  check('future year undo clears initial year', (await run('undo')).failedCount === 0 && date(initial).value === '');
  await fill(); date(initial).value = '1992'; date(initial).dataset.committed = '1992'; date(initial).dispatchEvent(new Event('input', { bubbles: true }));
  check('undo protects later user year edit', (await run('undo')).failedCount > 0 && date(initial).value === '1992');
  check('private source profile and other date fields remain unchanged', JSON.stringify(profile) === originalProfile && otherSnapshot() === others);
  return { adapter: 'feishu-years', checks, timings };
}
