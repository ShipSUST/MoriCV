export async function runMokaDateRegion() {
  if (location.hostname !== '127.0.0.1') throw new Error('Anonymous Moka fixture only');
  const fixture = globalThis.MokaDateRegionFixture;
  const checks = [],timings = [];
  const check = (name,ok) => {if (!ok) throw new Error(name);checks.push(name);globalThis.__recordProgress = {adapter:'moka-date-region',checks:[...checks],timings:[...timings]};};
  const settings = {overwriteExisting:false,confidenceThreshold:78,rejectedMatches:[]};
  const run = (command,payload = {}) => new Promise((resolve,reject) => {
    const started = performance.now(),timer = setTimeout(() => reject(new Error(`${command} timeout`)),114000);
    globalThis.__resumeHelperListener({type:'RESUME_HELPER_COMMAND',command,payload:{profile:{entries:[],records:{}},settings,...payload}},null,result => {
      clearTimeout(timer);timings.push({command,ms:Math.round(performance.now() - started)});result?.error ? reject(new Error(result.error)) : resolve(result);
    });
  });
  const value = key => fixture.snapshot().values[key];
  const fill = (key,entry,extra = {}) => {fixture.input(key).focus();return run('fillTarget',{entry:{id:`anonymous.${key}`,label:key,optionValues:[],...entry},...extra});};
  fixture.reset();
  const source = {value:'2001/04/19'}; const sourceSnapshot = JSON.stringify(source);
  const birthday = await fill('birthday',source);
  check('Moka month picker accepts a slash YMD and selects only source year and month',birthday.success && value('birthday') === '2001-04' && fixture.input('birthday').value === '2001-04');
  check('website alone supplies its internal first day',fixture.snapshot().internalDates.birthday === '2001-04-01');
  check('success result clearly reports month precision',JSON.stringify(birthday).includes('网站仅支持年月'));
  check('Moka month undo clears the committed display and model',(await run('undo')).failedCount === 0 && value('birthday') === '' && fixture.snapshot().internalDates.birthday === '');
  const monthOnly = await fill('birthday',{value:'1998-09'});
  check('source without a day is sufficient for an actual month-only picker',monthOnly.success && value('birthday') === '1998-09');
  check('month-only navigation crosses decade boundaries without inventing a date',(await run('undo')).failedCount === 0 && value('birthday') === '');
  const future = await fill('birthday',{value:'2042-12-30'});
  check('Moka month year navigation also moves forward',future.success && value('birthday') === '2042-12'); await run('undo');
  const equivalent = await fill('birthday',{value:'2024-02-29',pathValues:[['2024','2024年'],['2','二月'],['29']]});
  check('equivalent date path candidates coexist with month precision',equivalent.success && value('birthday') === '2024-02');await run('undo');
  const before = fixture.snapshot().commits.length;
  const conflicting = await fill('birthday',{value:'2024-02-29',pathValues:[['2023'],['二月'],['29']]});
  check('contradictory month date path fails before any commit',!conflicting.success && value('birthday') === '' && fixture.snapshot().commits.length === before);
  fixture.input('birthday').dataset.disabledMonth = '2024-02';
  const disabled = await fill('birthday',{value:'2024-02-29'});
  check('disabled Moka month is rejected rather than substituted',!disabled.success && value('birthday') === '');delete fixture.input('birthday').dataset.disabledMonth;
  fixture.input('birthday').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  fixture.input('birthday').dataset.rewrite = '2024-03';
  const rewritten = await fill('birthday',{value:'2024-02-29'});
  check('site-rewritten month never reports success',!rewritten.success);
  check('failed changed month is restored or remains available for exact undo',value('birthday') === '' || (await run('undo')).failedCount === 0 && value('birthday') === '');delete fixture.input('birthday').dataset.rewrite;
  fixture.setInitial('birthday','2002-03');
  const protectedValue = await fill('birthday',{value:'2003-04-29'});
  check('existing month requires explicit overwrite at month precision',protectedValue.requiresConfirmation && value('birthday') === '2002-03');
  const overwritten = await fill('birthday',{value:'2003-04-29'},{forceOverwrite:true});
  check('explicit overwrite selects the requested month',overwritten.success && value('birthday') === '2003-04');
  check('nonblank month undo restores its exact original model',(await run('undo')).failedCount === 0 && value('birthday') === '2002-03');
  await fill('birthday',{value:'2003-04-29'},{forceOverwrite:true});fixture.setInitial('birthday','2004-05');
  check('month undo preserves a later user edit',(await run('undo')).failedCount > 0 && value('birthday') === '2004-05');
  fixture.reset();
  fixture.input('birthday').click();await new Promise(resolve => setTimeout(resolve,45));
  const openedClicks = fixture.snapshot().clicks.birthday;
  const alreadyOpenDate = await fill('birthday',{value:'2024-09-15'});
  check('already open Moka month panel is reused without toggle closing',alreadyOpenDate.success && fixture.snapshot().clicks.birthday === openedClicks && value('birthday') === '2024-09');await run('undo');

  const entry = {value:'示例省甲示例市甲示例区甲',optionValues:['示例市甲','无关单级候选'],pathValues:[['示例省甲'],['示例市甲'],['示例区甲']]};
  const entryBefore = JSON.stringify(entry);
  const region = await fill('hometown',entry);
  check('Moka recognized region uses its path even when flat candidates are also configured',region.success && value('hometown') === entry.value);
  check('tabbed region commits only after local confirmation',fixture.snapshot().commits.at(-1).source === 'region-confirm');
  check('region blank undo clears committed data',(await run('undo')).failedCount === 0 && value('hometown') === '');
  fixture.input('hometown').click();await new Promise(resolve => setTimeout(resolve,45));
  const openedRegionClicks = fixture.snapshot().clicks.hometown;
  const alreadyOpenRegion = await fill('hometown',entry);
  check('already open region popup is not toggled closed',alreadyOpenRegion.success && fixture.snapshot().clicks.hometown === openedRegionClicks && value('hometown') === entry.value);await run('undo');
  fixture.dynamicRegion();
  const dynamicallyOpened = await fill('hometown',entry);
  check('previously unmounted region can be identified after opening the real input',dynamicallyOpened.success && value('hometown') === entry.value);
  check('dynamic region undo retains its confirmed identity after the popup unmounts',(await run('undo')).failedCount === 0 && value('hometown') === '');
  fixture.input('hometown').dataset.missingLevel = '2';
  const missing = await fill('hometown',entry);
  check('missing region level stops without flat candidate fallback or false success',!missing.success && value('hometown') === '' && /第 2 级/.test(missing.reason));delete fixture.input('hometown').dataset.missingLevel;
  fixture.input('hometown').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  fixture.input('hometown').dataset.ambiguousLevel = '1';
  const ambiguous = await fill('hometown',entry);
  check('ambiguous region option does not select the first duplicate',!ambiguous.success && value('hometown') === '');delete fixture.input('hometown').dataset.ambiguousLevel;
  fixture.input('hometown').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  const ordinary = await fill('single_city',{value:'不在选项中的主值',optionValues:['示例市乙','示例市甲'],pathValues:[['示例省甲'],['示例市甲'],['示例区甲']]});
  check('plain Moka select uses ordered flat candidates despite a configured region path',ordinary.success && value('single_city') === '示例市乙');
  check('plain select undo is preserved',(await run('undo')).failedCount === 0 && value('single_city') === '');
  check('source data and configured alternatives remain immutable',JSON.stringify(source) === sourceSnapshot && JSON.stringify(entry) === entryBefore);
  return {adapter:'moka-date-region',anonymous:true,checks,timings};
}
